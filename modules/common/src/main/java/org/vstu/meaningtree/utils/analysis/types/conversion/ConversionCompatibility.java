package org.vstu.meaningtree.utils.analysis.types.conversion;

/**
 * Результат проверки преобразования.
 * <p>
 * Три состояния, а не {@code boolean}, потому что «преобразование запрещено правилами языка» и
 * «анализ не смог узнать типы» — разные факты. Смешав их, статический анализатор выдаёт
 * доказанный диагноз там, где на самом деле не хватило данных: например, при неразрешённом
 * вызове, где тип параметра неизвестен.
 */
public enum ConversionCompatibility {
    /** Преобразование разрешено правилами языка. */
    COMPATIBLE,
    /** Преобразование запрещено: типы известны, и язык такой переход не допускает. */
    INCOMPATIBLE,
    /** Ответа нет: хотя бы один из типов не выведен либо цель вызова не найдена. */
    UNKNOWN
}
